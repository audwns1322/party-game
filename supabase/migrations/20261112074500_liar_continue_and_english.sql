update app_private.round_players p set hints_done=least(3,g.hint_index/c.n+case when p.turn_order<=g.hint_index%c.n then 1 else 0 end)
from app_private.rounds g cross join lateral(select count(*)::int n from app_private.round_players where round_id=g.id)c
where p.round_id=g.id and c.n>0;

