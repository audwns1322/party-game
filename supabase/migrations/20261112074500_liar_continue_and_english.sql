create or replace function app_private.pick_builtin_word(p_round uuid,p_settings jsonb) returns void
language plpgsql volatile security definer set search_path='' as $$
declare v_theme text:=coalesce(p_settings->>'theme','random');v_word text;v_easy text;v_hard text;v_liar text;v_en boolean:=coalesce(p_settings->>'language','ko')='en';
begin
 if v_theme='random' then
  select category into v_theme from (select distinct category from app_private.builtin_words where not v_en or category<>'크로스핏') t order by gen_random_uuid() limit 1;
 end if;
 if v_en then select word,easy_word,hard_word into v_word,v_easy,v_hard from app_private.builtin_words_en where category=v_theme order by gen_random_uuid() limit 1;
 else select word,easy_word,hard_word into v_word,v_easy,v_hard from app_private.builtin_words where category=v_theme order by gen_random_uuid() limit 1;end if;
 if v_word is null then raise exception 'INVALID_SETTINGS' using errcode='P0001';end if;
 if p_settings->>'game_mode'='confusion' then v_liar:=case when p_settings->>'difficulty'='hard' then v_hard else v_easy end;end if;
 insert into app_private.round_secrets(round_id,word,category,liar_word) values(p_round,v_word,v_theme,v_liar);
end; $$;
