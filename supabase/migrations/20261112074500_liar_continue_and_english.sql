create or replace function app_private.advance_connectivity(p_room uuid) returns boolean
language plpgsql volatile security definer set search_path='' as $$
declare r app_private.rooms;g app_private.rounds;v_now timestamptz:=clock_timestamp();v_next uuid;v_changed boolean:=false;
begin
 select * into r from app_private.rooms where id=p_room;
 if r.status<>'open' or r.expires_at<=now() then return false;end if;
 select * into g from app_private.rounds where room_id=p_room and ended_at is null;
 -- A departed host never takes the role back automatically. Waiters cannot inherit an active game.
 if exists(select 1 from app_private.players where id=r.host_player_id and (status='left' or last_seen_at<=v_now-interval '60 seconds')) then
  select p.id into v_next from app_private.players p where p.room_id=p_room and p.status<>'left' and p.id<>r.host_player_id
   and p.last_seen_at>v_now-interval '30 seconds'
   and (g.id is null or exists(select 1 from app_private.round_players rp where rp.round_id=g.id and rp.player_id=p.id and rp.eliminated_at is null))
   order by p.join_order limit 1;
  if v_next is not null then update app_private.rooms set host_player_id=v_next where id=p_room;v_changed:=true;end if;
 end if;

 -- Restore old paused liar rounds once; never pause the whole game for presence.
 if g.id is not null and r.game_type='liar' and g.phase='PAUSED_DISCONNECT' then
  update app_private.rounds set phase=disconnect_phase,phase_started_at=v_now,
    deadline_at=case when disconnect_remaining_ms is null then null else v_now+disconnect_remaining_ms*interval '1 millisecond' end,
    disconnect_phase=null,disconnect_remaining_ms=null,disconnect_grace_until=null,version=version+1 where id=g.id;
  update app_private.appeals set deadline_at=(select deadline_at from app_private.rounds where id=g.id)
    where guess_id=g.current_guess_id and g.disconnect_phase='APPEAL_VOTE';
  v_changed:=true;
 end if;
 if v_changed then perform app_private.bump(p_room);end if;
 return v_changed;
end; $$;

alter function app_private.room_dto(uuid,uuid) rename to room_dto_before_liar_continue;
create function app_private.room_dto(p_room uuid,p_me uuid) returns jsonb
language sql stable security definer set search_path='' as $$
 select case when g.id is null or base.value->'round' is null or base.value->'round'='null'::jsonb then base.value
 else base.value||jsonb_build_object('round',(base.value->'round')||jsonb_build_object(
  'language',coalesce(g.config->>'language','ko'),
  'current_player_id',case when g.phase='HINT' or (g.phase='PAUSED_HOST' and g.paused_phase='HINT') then app_private.liar_hint_speaker(g.id) else null end,
  'hint_pending_ids',case when g.phase='HINT' then coalesce((select jsonb_agg(rp.player_id order by rp.turn_order) from app_private.round_players rp where rp.round_id=g.id and rp.hints_done=g.hint_index/(select count(*)::int from app_private.round_players where round_id=g.id)),'[]'::jsonb) else '[]'::jsonb end,
  'away_ids',coalesce((select jsonb_agg(p.id order by p.join_order) from app_private.round_players rp join app_private.players p on p.id=rp.player_id where rp.round_id=g.id and rp.eliminated_at is null and (p.status='left' or p.last_seen_at<=statement_timestamp()-interval '30 seconds')),'[]'::jsonb)
 )) end
 from (select app_private.room_dto_before_liar_continue(p_room,p_me) value) base
 left join lateral(select * from app_private.rounds where room_id=p_room and (ended_at is null or phase='FINAL_RESULT') order by (ended_at is null) desc,created_at desc limit 1) g on true;
$$;

